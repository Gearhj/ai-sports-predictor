function normalizedName(name: string) {
  return name
    .normalize("NFKD")
    .replace(/[\u0300-\u036f]/g, "")
    .toLowerCase();
}

function mergeByName(...groups: Guitarist[][]) {
  const seen = new Set<string>();
  return groups.flatMap((group) =>
    group.filter((guitarist) => {
      const key = normalizedName(guitarist.name);
      if (seen.has(key)) return false;
      seen.add(key);
      return true;
    }),
  );
}

